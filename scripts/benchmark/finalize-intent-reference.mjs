import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const dir = process.argv[2];
if (!dir) throw new Error('Pass external benchmark directory');
const read = name => fs.readFileSync(path.join(dir, name), 'utf8').trim().split(/\r?\n/).filter(Boolean).map(JSON.parse);
const digest = name => crypto.createHash('sha256').update(fs.readFileSync(path.join(dir, name))).digest('hex');
const input = read('reference-input.jsonl');
const a = new Map(read('reference-a.jsonl').map(r => [r.id, r]));
const b = new Map(read('reference-b.jsonl').map(r => [r.id, r]));
const overrides = new Map(read('reference-adjudications.jsonl').map(r => [r.id, r]));
if (input.length !== 300 || a.size !== 300 || b.size !== 300) throw new Error('Reference coverage mismatch');
const sorted = x => JSON.stringify([...x].sort());
let decisionAgreements = 0, intentAgreements = 0;
const final = input.map(row => {
  const first = a.get(row.id), second = b.get(row.id), override = overrides.get(row.id);
  if (!first || !second) throw new Error('Missing reference id');
  const sameDecision = first.decision === second.decision;
  const sameIntents = sorted(first.intents) === sorted(second.intents);
  if (sameDecision) decisionAgreements++;
  if (sameIntents) intentAgreements++;
  if ((!sameDecision || !sameIntents) && !override) throw new Error(`Unresolved disagreement ${row.id}`);
  const chosen = override ?? first;
  if (!['ACCEPT', 'REJECT', 'UNCERTAIN'].includes(chosen.decision)) throw new Error('Invalid decision');
  if (!chosen.evidence || !row.text.includes(chosen.evidence) || [...chosen.evidence].length > 180) throw new Error(`Invalid exact evidence ${row.id}`);
  return { id: row.id, platform: row.platform, decision: chosen.decision, intents: chosen.intents,
    reason_code: chosen.reason_code, evidence: chosen.evidence,
    annotation_origin: override ? 'AI_ADJUDICATED' : 'AI_DOUBLE_REVIEW_AGREEMENT', human_validated: false,
    reviewer_a_decision: first.decision, reviewer_b_decision: second.decision,
    adjudication_note: override?.note ?? null, reference_status: 'AI_ADJUDICATED_NOT_HUMAN_VALIDATED' };
});
const counts = rows => Object.fromEntries(['ACCEPT', 'REJECT', 'UNCERTAIN'].map(k => [k, rows.filter(r => r.decision === k).length]));
const output = final.map(r => JSON.stringify(r)).join('\n') + '\n';
const target = path.join(dir, 'reference-final.jsonl');
if (fs.existsSync(target) && fs.readFileSync(target, 'utf8') !== output) throw new Error('Reference already frozen with different content');
fs.writeFileSync(target, output);
const summary = { frozen_at: new Date().toISOString(), reference_status: 'AI_ADJUDICATED_NOT_HUMAN_VALIDATED',
  count: final.length, decision_agreements_before_adjudication: decisionAgreements, agreement_rate: decisionAgreements / final.length,
  intent_agreements_before_adjudication: intentAgreements, adjudicated_records: overrides.size,
  counts: counts(final), by_platform: Object.fromEntries(['facebook', 'threads'].map(p => [p, counts(final.filter(r => r.platform === p))])),
  hashes: Object.fromEntries(['reference-input.jsonl', 'reference-a.jsonl', 'reference-b.jsonl', 'reference-adjudications.jsonl', 'reference-final.jsonl'].map(n => [n, digest(n)])),
  limitations: ['Reference labels generated by two independent AI contexts and AI adjudication, not human gold.', 'Agreement is not an accuracy estimate; shared-model biases can remain.', 'Text-only observable intent, not authenticity or hidden sponsorship.'] };
fs.writeFileSync(path.join(dir, 'reference-summary.json'), JSON.stringify(summary, null, 2));
const privateRows = new Map(read('records-private.jsonl').map(r => [r.id, r]));
fs.writeFileSync(path.join(dir, 'human-review.jsonl'), final.map(r => JSON.stringify({ ...r, text: privateRows.get(r.id).text, url: privateRows.get(r.id).url,
  human_decision: null, human_intents: null, human_notes: null, priority: overrides.has(r.id) || r.decision === 'UNCERTAIN' ? 'HIGH' : 'NORMAL' })).join('\n') + '\n');
console.log(JSON.stringify({ counts: summary.counts, by_platform: summary.by_platform, agreement_rate: summary.agreement_rate, adjudicated_records: overrides.size }));
